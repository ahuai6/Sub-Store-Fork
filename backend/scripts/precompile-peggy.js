/**
 * Compile the Surge, Loon, and QX Peggy grammars to parser source.
 *
 * Request-time peggy.generate() is paid again on every Surge script run.
 * The grammar in each peggy/*.js file stays the source of truth. This writes
 * a parser module next to it. Runtime getParser() loads that module and does
 * not call peggy.generate.
 *
 *   node scripts/precompile-peggy.js
 */
const fs = require('fs');
const path = require('path');
const peggy = require('peggy');

const root = path.join(__dirname, '..', 'src/core/proxy-utils/parsers/peggy');
const outDir = path.join(root, 'generated');

const targets = [
    {
        file: 'surge.js',
        sample:
            'Bench = ss, example.com, 8388, encrypt-method=aes-128-gcm, password=secret',
    },
    {
        file: 'loon.js',
        sample: 'Bench=shadowsocks,example.com,8388,aes-128-gcm,"secret"',
    },
    {
        file: 'qx.js',
        sample:
            'shadowsocks=example.com:8388, method=aes-128-gcm, password=secret, tag=Bench',
    },
];

function extractGrammar(source, file) {
    const header = 'export const grammars = String.raw`';
    const start = source.indexOf(header);
    const end = start < 0 ? -1 : source.indexOf('\n`;', start);
    if (start < 0 || end < 0) {
        throw new Error(`${file} is missing the grammar anchors`);
    }
    return source.slice(start + header.length, end);
}

function compileGrammar(grammar) {
    return peggy.generate(grammar, {
        output: 'source',
        format: 'bare',
    });
}

function parseBoth(grammar, source, sample) {
    const fresh = peggy.generate(grammar);
    const compiled = eval(source);
    let freshValue;
    let compiledValue;
    let freshError;
    let compiledError;
    try {
        freshValue = fresh.parse(sample);
    } catch (error) {
        freshError = error.message;
    }
    try {
        compiledValue = compiled.parse(sample);
    } catch (error) {
        compiledError = error.message;
    }
    if (freshError || compiledError) {
        if (freshError !== compiledError) {
            throw new Error(
                `sample mismatch\nfresh: ${freshError}\ncompiled: ${compiledError}`,
            );
        }
        return;
    }
    const left = JSON.stringify(freshValue);
    const right = JSON.stringify(compiledValue);
    if (left !== right) {
        throw new Error(`sample mismatch\n${left}\n${right}`);
    }
}

function precompilePeggy() {
    fs.mkdirSync(outDir, { recursive: true });
    for (const target of targets) {
        const sourcePath = path.join(root, target.file);
        const grammar = extractGrammar(
            fs.readFileSync(sourcePath, 'utf8'),
            target.file,
        );
        const bare = compileGrammar(grammar);
        if (bare.includes('sourceMappingURL')) {
            throw new Error(`${target.file} parser source includes a source map`);
        }
        parseBoth(grammar, bare, target.sample);
        const moduleSource =
            '// Generated by backend/scripts/precompile-peggy.js. Do not edit.\n' +
            'export default ' +
            bare +
            ';\n';
        const dest = path.join(outDir, target.file);
        fs.writeFileSync(dest, moduleSource);
    }
}

if (require.main === module) {
    precompilePeggy();
}

module.exports = { precompilePeggy };
